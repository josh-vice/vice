	expect(source).toContain("async function clickLadderPrice(side: 'buy' | 'sell', price: number, stop = false)");
	expect(source).toContain('if (!$clickPlacementMode)');
	expect(source).toContain('marketKey: $selectedMarket.marketKey');
	expect(source).toContain("type: stop ? 'stop' : 'limit'");
